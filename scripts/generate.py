"""Generate the SDK's operation table, types and resource classes from openapi.yaml.

Usage:
    uv run python scripts/generate.py           # write src/slidecold/_operations.py, types.py, _resources.py
    uv run python scripts/generate.py --check   # exit 1 if the committed output is stale
"""

from __future__ import annotations

import keyword
import pprint
import re
import sys
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi.yaml"
PKG = ROOT / "src" / "slidecold"
HEADER = "# Generated by scripts/generate.py from openapi.yaml. Do not edit by hand.\n"

HTTP_METHODS = ("get", "post", "put", "patch", "delete")
# Non-DELETE operations whose effect can't be undone (a DM is delivered on Instagram).
IRREVERSIBLE = {"sendConversationReply", "sendConversationPhoto"}
# Words dropped from operationIds to get the method name on a resource (`getCampaignStats` -> `campaigns.stats`).
RESOURCE_NOUNS = {
    "campaigns": {"campaign", "campaigns"},
    "audiences": {"audience", "audiences"},
    "conversations": {"conversation", "conversations"},
    "accounts": {"account", "accounts"},
    "proxies": {"proxy", "proxies"},
    "folders": {"folder", "folders"},
}


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[a-z])(?=[0-9])", "_", s)
    return s.replace("-", "_").lower()


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


class Gen:
    def __init__(self, spec: Dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: Dict[str, Any] = spec["components"]["schemas"]
        self.inline_bodies: Dict[str, Dict[str, Any]] = {}  # TypedDict name -> schema

    # ── $ref helpers ──
    def deref(self, obj: Dict[str, Any]) -> Dict[str, Any]:
        while "$ref" in obj:
            parts = obj["$ref"].lstrip("#/").split("/")
            node: Any = self.spec
            for p in parts:
                node = node[p]
            obj = node
        return obj

    def inline(self, schema: Any) -> Any:
        """Resolve every $ref so the schema is self-contained (for MCP input schemas)."""
        if isinstance(schema, dict):
            if "$ref" in schema:
                return self.inline(self.deref(schema))
            return {k: self.inline(v) for k, v in schema.items()}
        if isinstance(schema, list):
            return [self.inline(v) for v in schema]
        return schema

    # ── Python types ──
    def py_type(self, schema: Dict[str, Any]) -> str:
        if "$ref" in schema:
            return schema["$ref"].rsplit("/", 1)[1]
        for key in ("anyOf", "oneOf"):
            if key in schema:
                variants = [v for v in schema[key] if v.get("type") != "null"]
                nullable = len(variants) != len(schema[key])
                inner = self.py_type(variants[0]) if len(variants) == 1 else "Dict[str, Any]"
                return f"Optional[{inner}]" if nullable else inner
        if "allOf" in schema:
            return "Dict[str, Any]"
        t = schema.get("type")
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            inner = self.py_type({**schema, "type": non_null[0]}) if len(non_null) == 1 else "Any"
            return f"Optional[{inner}]" if "null" in t else inner
        if t == "string":
            if "enum" in schema:
                return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "float"
        if t == "boolean":
            return "bool"
        if t == "array":
            return f"List[{self.py_type(schema.get('items', {}))}]"
        if t == "object":
            ap = schema.get("additionalProperties")
            if isinstance(ap, dict) and ap:
                return f"Dict[str, {self.py_type(ap)}]"
            return "Dict[str, Any]"
        return "Any"

    def typeddict(self, name: str, schema: Dict[str, Any], bases: Optional[List[str]] = None) -> str:
        doc = schema.get("description", "").strip().replace('"""', "'''")
        lines = [f"class {name}({', '.join(bases or ['TypedDict'])}, total=False):"]
        if doc:
            lines.append(f'    """{doc}"""')
        props = schema.get("properties", {})
        for prop, sub in props.items():
            lines.append(f"    {prop}: {self.py_type(sub)}")
        if not props and not doc:
            lines.append("    pass")
        return "\n".join(lines)

    def emit_types(self) -> str:
        out = [
            HEADER,
            '"""TypedDicts for SlideCold API models and request bodies.\n\n'
            "All keys are optional (`total=False`); see openapi.yaml for which fields are required.\n"
            '"""\n',
            "from __future__ import annotations\n",
            "from typing import Any, Dict, List, Literal, Optional, TypedDict\n",
        ]
        names: List[str] = []
        for name, schema in self.schemas.items():
            names.append(name)
            if "allOf" in schema:
                bases = [p["$ref"].rsplit("/", 1)[1] for p in schema["allOf"] if "$ref" in p]
                extra: Dict[str, Any] = {"properties": {}}
                for part in schema["allOf"]:
                    if "$ref" not in part:
                        extra["properties"].update(part.get("properties", {}))
                extra["description"] = schema.get("description", "")
                out.append("\n" + self.typeddict(name, extra, bases) + "\n")
            elif schema.get("type") == "object":
                out.append("\n" + self.typeddict(name, schema) + "\n")
            else:
                out.append(f"\n{name} = {self.py_type(schema)}\n")
        for name, schema in self.inline_bodies.items():
            names.append(name)
            out.append("\n" + self.typeddict(name, schema) + "\n")
        out.insert(4, "__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n")
        return "\n".join(out)

    # ── operations ──
    def operations(self) -> List[Dict[str, Any]]:
        ops: List[Dict[str, Any]] = []
        for path, item in self.spec["paths"].items():
            shared = item.get("parameters", [])
            for method in HTTP_METHODS:
                if method not in item:
                    continue
                op = item[method]
                ops.append(self.operation(path, method, op, shared))
        seen = set()
        for o in ops:
            key = (o["resource"], o["name"])
            assert key not in seen, f"duplicate method {key}"
            seen.add(key)
        return ops

    def operation(self, path: str, method: str, op: Dict[str, Any], shared: List[Any]) -> Dict[str, Any]:
        op_id: str = op["operationId"]
        resource = op["tags"][0].lower()
        words = [w for w in snake(op_id).split("_") if w not in RESOURCE_NOUNS[resource]]
        if words[0] == "get" and len(words) > 1:
            words = words[1:]
        name = "_".join(words)
        assert not keyword.iskeyword(name), name

        params = [self.deref(p) for p in shared + op.get("parameters", [])]

        def param(p: Dict[str, Any]) -> Dict[str, Any]:
            return {
                "name": p["name"],
                "py_name": snake(p["name"]),
                "required": bool(p.get("required", p["in"] == "path")),
                "schema": self.inline(p.get("schema", {})),
                "description": p.get("description", ""),
            }

        path_params = [param(p) for p in params if p["in"] == "path"]
        query_params = [param(p) for p in params if p["in"] == "query"]

        body_kind = None
        body_schema = None
        body_type = None
        file_field = None
        body_required = False
        rb = op.get("requestBody")
        if rb:
            content = rb["content"]
            body_required = bool(rb.get("required", False))
            if "multipart/form-data" in content:
                mp = content["multipart/form-data"]["schema"]
                file_field = next(k for k, v in mp["properties"].items() if "contentMediaType" in v)
            if "application/json" in content:
                raw = content["application/json"]["schema"]
                body_schema = self.inline(raw)
                if "$ref" in raw:
                    body_type = raw["$ref"].rsplit("/", 1)[1]
                elif raw.get("type") == "object":
                    body_type = pascal(op_id) + "Body"
                    self.inline_bodies[body_type] = raw
                else:
                    body_type = "Dict[str, Any]"
            body_kind = (
                "json_or_multipart" if file_field and body_schema else "multipart" if file_field else "json"
            )

        param_names = {p["name"] for p in path_params + query_params} | {"file_path", "body"}
        body_flat = bool(
            body_schema
            and body_schema.get("type") == "object"
            and not set(body_schema.get("properties", {})) & param_names
        )

        responses = op.get("responses", {})
        ok = [self.deref(responses[c]) for c in sorted(responses) if c.startswith("2")]
        ctypes = set()
        result_type = "Any"
        for r in ok:
            for ct, media in (r.get("content") or {}).items():
                ctypes.add(ct)
                if ct == "application/json" and result_type == "Any":
                    result_type = self.py_type(media.get("schema", {}))
        if ctypes == {"text/csv"}:
            result_type = "str"
        elif len(ctypes) > 1 or len(ok) > 1:
            result_type = "Any"

        return {
            "id": op_id,
            "method": method.upper(),
            "path": path,
            "resource": resource,
            "name": name,
            "tool": snake(op_id),
            "summary": op.get("summary", ""),
            "description": (op.get("description") or "").strip(),
            "scope": op.get("x-required-scope", ""),
            "path_params": path_params,
            "query_params": query_params,
            "body": body_kind,
            "body_required": body_required,
            "body_schema": body_schema,
            "body_flat": body_flat,
            "body_type": body_type,
            "file_field": file_field,
            "result_type": result_type,
            "destructive": method == "delete" or op_id in IRREVERSIBLE,
        }

    def emit_operations(self, ops: List[Dict[str, Any]]) -> str:
        public_keys = [
            "id", "method", "path", "resource", "name", "tool", "summary", "description", "scope",
            "path_params", "query_params", "body", "body_required", "body_schema", "body_flat",
            "file_field", "destructive",
        ]  # fmt: skip
        rows = [{k: o[k] for k in public_keys} for o in ops]
        table = textwrap.indent(pprint.pformat(rows, width=110, sort_dicts=False), "    ")[4:]
        return (
            HEADER
            + '"""The SlideCold API operation table (one entry per OpenAPI operation)."""\n\n'
            + "from typing import Any, Dict, List, NamedTuple, Optional, Tuple\n\n\n"
            + "class Param(NamedTuple):\n"
            + "    name: str\n    py_name: str\n    required: bool\n    schema: Dict[str, Any]\n    description: str\n\n\n"
            + "class Operation(NamedTuple):\n"
            + "    id: str\n    method: str\n    path: str\n    resource: str\n    name: str\n    tool: str\n"
            + "    summary: str\n    description: str\n    scope: str\n"
            + "    path_params: Tuple[Param, ...]\n    query_params: Tuple[Param, ...]\n"
            + "    body: Optional[str]  # None, 'json', 'multipart' or 'json_or_multipart'\n"
            + "    body_required: bool\n    body_schema: Optional[Dict[str, Any]]\n"
            + "    body_flat: bool  # MCP: body properties are top-level tool arguments\n"
            + "    file_field: Optional[str]  # multipart field name for the uploaded file\n"
            + "    destructive: bool\n\n\n"
            + "# Resource name -> description, from the OpenAPI tags.\n"
            + f"RESOURCES: Dict[str, str] = {pprint.pformat(self.resources(), width=110, sort_dicts=False)}\n\n"
            + f"_TABLE: List[Dict[str, Any]] = {table}\n\n"
            + "OPERATIONS: Dict[str, Operation] = {\n"
            + "    row['id']: Operation(**{\n"
            + "        **row,\n"
            + "        'path_params': tuple(Param(**p) for p in row['path_params']),\n"
            + "        'query_params': tuple(Param(**p) for p in row['query_params']),\n"
            + "    })\n"
            + "    for row in _TABLE\n"
            + "}\n"
        )

    def resources(self) -> Dict[str, str]:
        return {t["name"].lower(): t.get("description", "") for t in self.spec.get("tags", [])}

    # ── resource classes ──
    def method_code(self, o: Dict[str, Any], is_async: bool) -> str:
        args = ["self"]
        pos_only = [f"{p['py_name']}: str" for p in o["path_params"]]
        if o["body"] in ("json", "json_or_multipart"):
            pos_only.append(f"body: Optional[{o['body_type']}] = None")
        if pos_only:
            args += pos_only + ["/"]
        kw = []
        for p in o["query_params"]:
            t = self.query_type(p)
            kw.append(f"{p['py_name']}: {t}" if p["required"] else f"{p['py_name']}: Optional[{t}] = None")
        if o["body"] == "multipart":
            kw.insert(0, "file: FileInput")
        elif o["body"] == "json_or_multipart":
            kw.append("file: Optional[FileInput] = None")
        if kw:
            if not any(p["required"] for p in o["query_params"]) or o["body"]:
                args.append("*")
            args += kw
        if o["body"] in ("json", "json_or_multipart"):
            args.append("**fields: Any")

        doc = [o["summary"] + "."]
        if o["description"]:
            doc += ["", *o["description"].splitlines()]
        if o["body"] in ("json", "json_or_multipart"):
            doc += ["", "The JSON body can be passed as a dict, as keyword arguments, or both."]
        if o["body"] in ("multipart", "json_or_multipart"):
            doc += ["", "`file` is a path, bytes, a binary file object or a (filename, content) tuple."]
        doc += ["", f"Scope: ``{o['scope']}``. HTTP: ``{o['method']} {o['path']}``."]
        doc_text = (
            "\n".join(("        " + d if d else "") for d in doc).replace("\\", "\\\\").replace('"""', "'''")
        )

        call = [repr(o["id"])]
        if o["path_params"]:
            call.append(
                "path={" + ", ".join(f"{p['name']!r}: {p['py_name']}" for p in o["path_params"]) + "}"
            )
        if o["query_params"]:
            call.append(
                "query={" + ", ".join(f"{p['name']!r}: {p['py_name']}" for p in o["query_params"]) + "}"
            )
        if o["body"] in ("json", "json_or_multipart"):
            call.append("body=_merge(body, fields)")
        if o["body"]:
            call.append("file=file" if o["file_field"] else "")
        call = [c for c in call if c]
        ret = o["result_type"]
        prefix = "async def" if is_async else "def"
        ignore = "" if ret == "Any" else "  # type: ignore[no-any-return]"
        aw = "await " if is_async else ""
        signature = f"    {prefix} {o['name']}({', '.join(args)}) -> {ret}:"
        if len(signature) > 110:
            signature = (
                f"    {prefix} {o['name']}(\n" + "".join(f"        {a},\n" for a in args) + f"    ) -> {ret}:"
            )
        return (
            f'{signature}\n        """{doc_text.lstrip()}\n        """\n'
            f"        return {aw}self._client.request({', '.join(call)}){ignore}\n"
        )

    @staticmethod
    def query_type(p: Dict[str, Any]) -> str:
        s = p["schema"]
        if s.get("enum") == ["true", "false"]:
            return "bool"
        if "enum" in s:
            return "Literal[" + ", ".join(repr(v) for v in s["enum"]) + "]"
        return {"integer": "int", "number": "float", "boolean": "bool"}.get(s.get("type", ""), "str")

    def emit_resources(self, ops: List[Dict[str, Any]]) -> str:
        resources: Dict[str, List[Dict[str, Any]]] = {}
        for o in ops:
            resources.setdefault(o["resource"], []).append(o)
        out = [
            HEADER,
            '"""Resource classes: `client.campaigns`, `client.accounts`, ..."""\n',
            "from __future__ import annotations\n",
            "from typing import TYPE_CHECKING, Any, Dict, List, Literal, Optional\n",
            "from ._files import FileInput",
            "from .types import (\n__TYPE_IMPORTS__)\n",
            "if TYPE_CHECKING:",
            "    from ._client import AsyncSlideCold, SlideCold\n\n",
            "def _merge(body: Optional[Any], fields: Dict[str, Any]) -> Optional[Dict[str, Any]]:",
            "    if body is None and not fields:",
            "        return None",
            "    return {**(body or {}), **fields}\n",
        ]
        tags = self.resources()
        for is_async in (False, True):
            client_type = "AsyncSlideCold" if is_async else "SlideCold"
            for res, rops in resources.items():
                cls = ("Async" if is_async else "") + pascal(res)
                out.append(f"\nclass {cls}:")
                out.append(f'    """{tags.get(res, res)}"""\n')
                out.append(f"    def __init__(self, client: {client_type}) -> None:")
                out.append("        self._client = client\n")
                for o in rops:
                    out.append(self.method_code(o, is_async))
            mixin = "AsyncResources" if is_async else "SyncResources"
            out.append(f"\nclass {mixin}:")
            for res in resources:
                out.append(f"    {res}: {'Async' if is_async else ''}{pascal(res)}")
            out.append("\n    def _init_resources(self) -> None:")
            for res in resources:
                out.append(
                    f"        self.{res} = {'Async' if is_async else ''}{pascal(res)}(self)  # type: ignore[arg-type]"
                )
            out.append("")
        text = "\n".join(out) + "\n"
        used = sorted(
            n for n in self.type_names() if re.search(rf"\b{n}\b", text.split("__TYPE_IMPORTS__")[1])
        )
        return text.replace("__TYPE_IMPORTS__", "".join(f"    {n},\n" for n in used))

    def type_names(self) -> List[str]:
        return [*self.schemas, *self.inline_bodies]


def generate() -> Dict[Path, str]:
    gen = Gen(yaml.safe_load(SPEC.read_text()))
    ops = gen.operations()
    return {
        PKG / "_operations.py": gen.emit_operations(ops),
        PKG / "_resources.py": gen.emit_resources(ops),
        PKG / "types.py": gen.emit_types(),  # after operations(): it includes inline body TypedDicts
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in generate().items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Generated files are stale; run `uv run python scripts/generate.py`:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
